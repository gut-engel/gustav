# --- local weights refine the numbers -------------------------------------
def test_a_downloaded_config_json_replaces_the_ladders_numbers(service_factory, paths, ladder):
    reference = ladder.model("qwen3-4b")
    directory = paths.models / "qwen3-4b"
    directory.mkdir(parents=True)
    (directory / "config.json").write_text(
        json.dumps({
            "model_type": "qwen3", "num_hidden_layers": reference.layers,
            "hidden_size": reference.hidden, "num_attention_heads": reference.attn_heads,
            "num_key_value_heads": reference.kv_heads, "head_dim": reference.head_dim,
            "intermediate_size": reference.intermediate, "vocab_size": reference.vocab,
            "tie_word_embeddings": True,
        }),
        encoding="utf-8",
    )
    service = service_factory()
    refined = service._ladder_with_local_configs().model("qwen3-4b")
    assert refined.verified
    plan = service.ensure_plan().plan
    assert not any("ladder.yaml, not from a downloaded" in w for w in plan.warnings)


def test_an_unreadable_config_json_does_not_stop_startup(service_factory, paths, events):
    directory = paths.models / "qwen3-4b"
    directory.mkdir(parents=True)
    (directory / "config.json").write_text("{not json", encoding="utf-8")
    outcome = service_factory().ensure_plan()
    assert outcome.plan is not None
    assert any(e["kind"] == "hardware.config_unreadable" for e in events.recent())


