def test_a_pinned_plan_is_used_as_is(service_factory):
    pinned = {
        "base_model": "qwen3-1.7b", "repo": "Qwen/Qwen3-1.7B", "quantization": "4bit-nf4",
        "max_seq_len": 1024, "kv_cache_dtype": "int8", "compute_dtype": "float16",
        "attention": "sdpa", "lora_rank": 8, "train_seq_len": 512, "batch_size": 1,
        "grad_accum": 16, "gradient_checkpointing": True, "optimizer": "paged_adamw_8bit",
        "speculative_decoding": False, "draft_model": None, "inference_gpus": [0],
        "training_gpus": [], "training_allowed": False, "training_strategy": "none",
        "expansion": {"max_adapters": 2, "max_lora_rank": 8, "max_total_adapter_params": 0,
                      "max_adapter_vram_mb": 64, "warm_cache_mb": 1024, "cold_storage_mb": 2048},
    }
    outcome = service_factory(plan=pinned).ensure_plan()
    assert outcome.source == "config"
    assert outcome.plan.base_model == "qwen3-1.7b"
    assert outcome.plan.kv_cache_dtype == "int8"
    assert "will not override it" in outcome.plan.explanation[0]


