"""The verifier: run the code and see.

The point of this module is that a practice result is a *measurement*. The model
proposes a solution; the interpreter and the task's own asserts decide whether it was
right. Nothing here asks a model to grade anything.

What it actually guarantees, stated plainly so it is not mistaken for more:

* **A wall-clock timeout**, then SIGKILL to the whole process group — an infinite loop
  costs seconds, not a night, and a child that spawns children does not outlive it.
* **Resource limits** via ``RLIMIT_AS``, ``RLIMIT_CPU``, ``RLIMIT_NOFILE`` and
  ``RLIMIT_FSIZE``, so an allocation storm or a log bomb hits a ceiling rather than the
  machine's memory. They are set by the program's own prelude rather than by a
  ``preexec_fn``: a step process has torch's threads in it, and running Python between
  fork and exec in a threaded process is a documented way to deadlock. Soft and hard
  limits are set to the same value, so the candidate code cannot raise them again.
* **A throwaway working directory** and an almost empty environment, so code that
  writes files writes them where nobody will read them, and ``-I`` keeps it from
  importing anything out of the project.
* **A prelude that blocks sockets and subprocesses.** This is a guardrail against
  self-generated code that casually reaches for the network — not a security boundary.
  The code being run here is generated by a local model from local documentation; if
  you intend to run *untrusted* code, put a container or a seccomp filter under this
  class, which is why everything it does goes through one ``_spawn`` method.
"""

from __future__ import annotations

import os
import resource
import signal
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path

#: Prepended to every python program. Keeps accidents in.
#: Prepended to every python program. Applies the limits and keeps accidents in.
PRELUDE_TEMPLATE = """\
import builtins as _b, sys as _s, resource as _r
for _which, _value in (
    ("RLIMIT_AS", {memory_bytes}),
    ("RLIMIT_DATA", {memory_bytes}),
    ("RLIMIT_CPU", {cpu_seconds}),
    ("RLIMIT_NOFILE", 64),
    ("RLIMIT_FSIZE", {file_bytes}),
    ("RLIMIT_NPROC", 64),
):
    _limit = getattr(_r, _which, None)
    if _limit is None or not _value:
        continue
    try:
        _r.setrlimit(_limit, (_value, _value))   # hard limit too: not raisable again
    except (ValueError, OSError):
        pass
def _blocked(name):
    def _fail(*a, **k):
        raise RuntimeError(f"{{name}} is not available in the practice sandbox")
    return _fail
try:
    import socket as _sock
    _sock.socket = _blocked("socket")
    _sock.create_connection = _blocked("socket")
except Exception:
    pass
try:
    import subprocess as _sp
    _sp.Popen = _blocked("subprocess")
    _sp.run = _blocked("subprocess")
except Exception:
    pass
try:
    import os as _os
    for _name in ("system", "popen", "fork", "forkpty", "execv", "execve", "execvp",
                  "spawnv", "spawnve", "posix_spawn"):
        if hasattr(_os, _name):
            setattr(_os, _name, _blocked("os." + _name))
except Exception:
    pass
_s.setrecursionlimit(3000)
"""


@dataclass
class SandboxResult:
    passed: bool
    returncode: int | None = None
    stdout: str = ""
    stderr: str = ""
    duration_ms: int = 0
    timed_out: bool = False
    error: str = ""

    @property
    def detail(self) -> str:
        """A short, human-readable reason, for the attempt log and the report."""
        if self.passed:
            return "passed"
        if self.timed_out:
            return f"timed out after {self.duration_ms} ms"
        if self.error:
            return self.error
        tail = (self.stderr or self.stdout).strip().splitlines()
        return tail[-1][:300] if tail else f"exit code {self.returncode}"


class Sandbox:
    def __init__(
        self,
        *,
        python: str | None = None,
        timeout_seconds: float = 10.0,
        memory_limit_mb: int = 1024,
        max_output_bytes: int = 64 * 1024,
        workdir: Path | None = None,
        isolate_env: bool = True,
    ):
        self.python = python or sys.executable
        self.timeout_seconds = timeout_seconds
        self.memory_limit_mb = memory_limit_mb
        self.max_output_bytes = max_output_bytes
        self.workdir = workdir
        self.isolate_env = isolate_env

    def prelude(self) -> str:
        return PRELUDE_TEMPLATE.format(
            memory_bytes=max(self.memory_limit_mb, 0) * 1024 * 1024,
            cpu_seconds=max(int(self.timeout_seconds) + 1, 1),
            file_bytes=16 * 1024 * 1024,
        )

    # --- the one place a process is started -----------------------------
    def _spawn(self, script: Path, cwd: Path) -> SandboxResult:
        env: dict[str, str] = {
            "PATH": "/usr/bin:/bin",
            "HOME": str(cwd),
            "TMPDIR": str(cwd),
            "LC_ALL": "C.UTF-8",
            "PYTHONIOENCODING": "utf-8",
            "PYTHONDONTWRITEBYTECODE": "1",
        }
        if not self.isolate_env:
            env = {**os.environ, **env}
        started = time.monotonic()
        try:
            process = subprocess.Popen(
                [self.python, "-I", str(script)],
                cwd=str(cwd),
                env=env,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                errors="replace",
                # Its own session, so a timeout can kill anything it started too.
                start_new_session=True,
            )
        except OSError as exc:
            return SandboxResult(passed=False, error=f"could not start the sandbox: {exc}")

        timed_out = False
        try:
            stdout, stderr = process.communicate(timeout=self.timeout_seconds)
        except subprocess.TimeoutExpired:
            timed_out = True
            self._kill(process)
            stdout, stderr = process.communicate()
        duration_ms = int((time.monotonic() - started) * 1000)
        return SandboxResult(
            passed=(not timed_out and process.returncode == 0),
            returncode=process.returncode,
            stdout=(stdout or "")[: self.max_output_bytes],
            stderr=(stderr or "")[: self.max_output_bytes],
            duration_ms=duration_ms,
            timed_out=timed_out,
        )

    @staticmethod
    def _kill(process: subprocess.Popen) -> None:
        for sig in (signal.SIGKILL,):
            try:
                os.killpg(os.getpgid(process.pid), sig)
            except (ProcessLookupError, PermissionError, OSError):
                try:
                    process.kill()
                except ProcessLookupError:
                    pass

    # --- running python -------------------------------------------------
    def run_python(self, code: str, *, setup: str = "", tests: str = "") -> SandboxResult:
        """Run ``setup``, then ``code``, then ``tests``. Passing means exit code 0.

        The three parts are concatenated into one program on purpose: the tests have to
        see the names the candidate code defined, and a task's asserts are the only
        thing that decides whether it passed.
        """
        if not (code or "").strip():
            return SandboxResult(passed=False, error="there was no code to run")
        program = "\n\n".join(
            part
            for part in (self.prelude(), setup.strip(), code.strip(), tests.strip())
            if part
        )
        with tempfile.TemporaryDirectory(
            prefix="gustav-sandbox-", dir=str(self.workdir) if self.workdir else None
        ) as tmp:
            cwd = Path(tmp)
            script = cwd / "candidate.py"
            script.write_text(program + "\n", encoding="utf-8")
            return self._spawn(script, cwd)

    def check_imports(self, code: str) -> SandboxResult:
        """Does it even parse? A syntax error is not worth a process."""
        try:
            compile(code, "<candidate>", "exec")
        except SyntaxError as exc:
            return SandboxResult(passed=False, error=f"SyntaxError: {exc.msg} (line {exc.lineno})")
        return SandboxResult(passed=True)
